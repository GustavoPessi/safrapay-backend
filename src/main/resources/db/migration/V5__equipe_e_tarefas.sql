-- =============================================================================
-- V5 - Multiusuario: equipe (convites e papeis) + ciclo de vida da anotacao
--      de maquina como tarefa (06/10/2026). Contrato no Notion: "Contrato do
--      Multiusuario - equipe, convites, papeis e tarefas".
--
-- Papeis: DONO (quem nao e membro de equipe nenhuma), GERENTE e COLABORADOR.
-- Gerente e colaborador trabalham nos dados do dono da equipe; os dados
-- proprios deles continuam nas tabelas, so ficam escondidos enquanto forem
-- membros.
-- =============================================================================

CREATE TABLE public.equipe_membro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid character varying(36) NOT NULL UNIQUE,
    dono_usuario_id bigint NOT NULL REFERENCES public.usuario(id) ON DELETE CASCADE,
    -- null enquanto o convidado ainda nao tem conta (o convite e casado pelo e-mail)
    membro_usuario_id bigint REFERENCES public.usuario(id) ON DELETE CASCADE,
    email character varying(255) NOT NULL,
    papel character varying(20) NOT NULL CHECK (papel IN ('GERENTE', 'COLABORADOR')),
    status character varying(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'ACEITO', 'RECUSADO', 'CANCELADO', 'REMOVIDO', 'SAIU')),
    criado_em timestamp(6) with time zone NOT NULL,
    atualizado_em timestamp(6) with time zone NOT NULL,
    respondido_em timestamp(6) with time zone
);

-- Um convite ativo (pendente ou aceito) por dono + e-mail.
CREATE UNIQUE INDEX uq_equipe_convite_ativo
    ON public.equipe_membro (dono_usuario_id, lower(email))
    WHERE status IN ('PENDENTE', 'ACEITO');
-- Cada pessoa e membro aceito de no maximo 1 equipe.
CREATE UNIQUE INDEX uq_equipe_membro_aceito
    ON public.equipe_membro (membro_usuario_id)
    WHERE status = 'ACEITO';
CREATE INDEX idx_equipe_dono ON public.equipe_membro (dono_usuario_id);
CREATE INDEX idx_equipe_email_pendente ON public.equipe_membro (lower(email)) WHERE status = 'PENDENTE';

-- Anotacao de maquina vira tarefa. "concluida" (V3) continua sendo o status
-- (pendente/realizada); "atrasada" nao e guardada: concluida = false e prazo < hoje.
ALTER TABLE public.anotacao_maquina
    ADD COLUMN prazo date,
    ADD COLUMN responsavel_usuario_id bigint REFERENCES public.usuario(id) ON DELETE SET NULL,
    ADD COLUMN concluido_em timestamp(6) with time zone,
    ADD COLUMN concluido_por_usuario_id bigint REFERENCES public.usuario(id) ON DELETE SET NULL,
    ADD COLUMN criado_por_usuario_id bigint REFERENCES public.usuario(id) ON DELETE SET NULL;

CREATE INDEX idx_anotacao_responsavel ON public.anotacao_maquina (responsavel_usuario_id);
