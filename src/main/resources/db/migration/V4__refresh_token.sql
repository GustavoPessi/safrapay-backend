-- =============================================================================
-- V4 - Refresh token (01/10/2026, contrato v2 da IA, item 9)
--
-- O JWT de acesso vale 24h e o app nao renovava: depois disso chat e sync
-- davam 403 ate o produtor sair e entrar de novo. Agora o login devolve tambem
-- um refresh token (90 dias) que o app troca em POST /api/auth/refresh por um
-- JWT novo + um refresh token novo (rotacao).
--
-- So o hash SHA-256 do refresh token fica no banco (quem ler a tabela nao
-- consegue usar os tokens). Tabela so do backend, nao sincroniza com o app.
-- =============================================================================

CREATE TABLE public.refresh_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES public.usuario(id) ON DELETE CASCADE,
    token_hash character varying(64) NOT NULL UNIQUE,
    data_criacao timestamp(6) with time zone NOT NULL,
    data_expiracao timestamp(6) with time zone NOT NULL,
    -- preenchida quando o token foi trocado (rotacao), no logout ou na troca de senha
    data_revogacao timestamp(6) with time zone,
    -- hash do token que substituiu este na rotacao (null = revogado por logout/senha)
    substituido_por_hash character varying(64)
);

CREATE INDEX idx_refresh_token_usuario ON public.refresh_token (usuario_id);
